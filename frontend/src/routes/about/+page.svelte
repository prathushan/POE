  <h1>About the Proxy Open Exchange</h1>

  <p>
    The Proxy Open Exchange (POE) is an open, community-driven platform that
    provides shareholders with a public venue to publish shareholder proposals
    and related documents, including no-action notices, exempt solicitations,
    and proxy inclusion status.
  </p>

  <h2>What you can publish on POE</h2>

  <ul class="publish-list">
    <li>
      <strong>Shareholder proposals.</strong> The full proposal can be published
      as a PDF, with the resolved clause as searchable text; the company and its
      CIK; the proposal topic; and the estimated annual meeting date. New
      proposals are reviewed by POE for credentials before publishing to avoid
      spam on the website.
    </li>
    <li>
      <strong>No-action notices.</strong> A company's notice to exclude a
      shareholder proposal can be published as a pdf. The basis for a company's
      exclusion notice should be chosen from the drop down menu and the notice
      date provided; and your response (if any) attached.
    </li>
    <li>
      <strong>Exempt solicitations.</strong> Exempt solicitations (proxy memos)
      can be attached as a pdf to your relevant proposal.
    </li>
    <li>
      <strong>Proxy status.</strong> Once the company's proxy statement is out,
      return to POE to provide the DEF 14A link and proposal item number, if
      posted, and mark the proposal as Included. Alternatively, mark the proposal
      Excluded, or Withdrawn, as appropriate, so the public record stays current.
    </li>
  </ul>

  <h2>Why POE Exists</h2>

  <p>
    The Proxy Open Exchange is a response to the SEC's retreat from the
    shareholder proposal process. In January 2025, the Division of Corporation
    Finance revised Compliance &amp; Disclosure Interpretation Question 126.06,
    barring shareholders with less than $5 million in a company's stock from
    posting their exempt solicitations on EDGAR. The agency has since gone
    further, stepping back from the no-action process that once addressed every
    attempt by a company to exclude a proposal. Recently it stated that it
    intends to rescind the federal shareholder proposal proxy process. Each step
    has the same effect: less voice for shareholders and less accountability for
    the companies they own. POE exists to create an independent public record of
    shareholder concerns and company responsiveness to its share owners. The site
    is built and maintained by shareholders themselves, so that the proposal
    process stays visible, independent of abdication by the market's regulators.
  </p>

  <h2>How Verification Works</h2>

  <ul>
    <li>Filers provide their SEC-issued CIK during registration.</li>
    <li>The CIK is cross-referenced against SEC EDGAR data.</li>
    <li>The filer's email domain is validated.</li>
    <li>Only verified proponents can submit filings.</li>
    <li>
      Only the organization that filed a proposal (or a POE administrator) can
      attach documents to it or update its proxy status.
    </li>
  </ul>

  <h2>Key Regulatory References</h2>

  <ul>
    <li><strong>Rule 14a-8</strong> — Shareholder proposal filing process &amp; proxy inclusion requirements.</li>
    <li><strong>Rule 14a-6(g)</strong> — Requires exempt filings.</li>
    <li><strong>Rule 14a-2(b)(1)</strong> — Exemption rules.</li>
    <li><strong>Rule 14a-101</strong> — SEC definitions.</li>
  </ul>

